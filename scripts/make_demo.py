"""Captures the demo as a REAL transcript (no editing): runs the CLI against real ngspice and writes docs/DEMO.md.  python scripts/make_demo.py"""
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
tmp = Path(tempfile.mkdtemp(prefix="tinyspice_demo_"))
db, runs = str(tmp / "p.sqlite"), str(tmp / "runs")
env = {**os.environ, "PYTHONIOENCODING": "utf-8"}
blocks = []


def sh(title, args, note=""):
    p = subprocess.run([sys.executable, "-m", "tinyspice", "--db", db, "--runs", runs, *args], capture_output=True, text=True, cwd=ROOT, env=env, encoding="utf-8")
    out = (p.stdout + p.stderr).replace("\r\n", "\n").strip()
    out = out.replace(str(ROOT), "<repo>").replace(str(tmp), "<tmp>")
    shown = "python -m tinyspice " + " ".join(a if " " not in a else '"' + a + '"' for a in args)
    blocks.append(f"### {title}\n{note}\n\n```\n$ {shown}\n{out}\n```\n(exit code {p.returncode})\n")
    return out, p.returncode


req_ok = f"file:{ROOT / 'examples' / 'requests' / 'idvg_complete.txt'}"
req_bad = f"file:{ROOT / 'examples' / 'requests' / 'idvg_example.txt'}"
ok_text = (ROOT / "examples" / "requests" / "idvg_complete.txt").read_text().strip()
bad_text = (ROOT / "examples" / "requests" / "idvg_example.txt").read_text().strip()

out, _ = sh("1. Ask in plain English (the parser extracts; code validates; real ngspice runs)", ["ask", req_ok], f"Request: _{ok_text}_")
rid = re.search(r"run_id\s*:\s*(\S+)", out).group(1)
sh("2. Every recorded artefact is hash-checked", ["verify", rid])
sh("3. Replay the stored run and compare measurements (rtol 1e-6)", ["replay", rid])
sh("4. An incomplete request is refused before anything is simulated", ["ask", req_bad], f"Request: _{bad_text}_ (no width, no temperature stated).")
sh("5. A physically absurd request is refused by the planner (ngspice itself would happily simulate it)", ["ask", "Characterize an NMOS SKY130 NFET with W = 1 um and L = 0.18 um at 300 degrees Celsius. Id-Vg with VDS fixed at 1.8 V, VGS from 0 to 1.8 V in 0.02 V steps. Measure the threshold voltage. At most 100 points."])
sh("6. The run history", ["runs"])
doc = ("# TinySPICE demo (real transcript)\n\nGenerated by `scripts/make_demo.py` from real runs on real ngspice 47 + SKY130; nothing is edited. "
       "The parser is the rule-based floor here (canonical phrasings); the local-LLM parser is selected with `--parser llm:<model>`. Run ids and timings differ per run.\n\n" + "\n".join(blocks))
(ROOT / "docs" / "DEMO.md").write_text(doc, encoding="utf-8", newline="\n")
print("wrote docs/DEMO.md", len(doc), "chars")
